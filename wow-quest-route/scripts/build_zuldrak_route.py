def fb(*qids: int) -> str:
    rows: list[str] = []
    for qid in qids:
        for code in (MECH.get(qid) or {}).get("fivebox_checks") or []:
            text = FB_TEXT.get(code, code)
            if text not in rows:
                rows.append(text)
    return "；".join(rows)


points: list[list[Any]] = []
covered: set[int] = set()
step_groups: list[dict[str, Any]] = []


def P(
    x: float,
    y: float,
    title: str,
    action: str,
    phase: str,
    note: str = "",
    movement: str = "ride",
    qids: tuple[int, ...] = (),
    optional: bool = False,
    fivebox_check: str = "",
) -> None:
    points.append([x, y, title, action, phase, note, movement, optional, fivebox_check])
    covered.update(qids)


def G(title: str, summary: str, fn) -> None:
    start = len(points)
    fn()
    end = len(points) - 1
    if end < start:
        raise RuntimeError(f"empty group: {title}")
    step_groups.append({"start": start, "end": end, "title": title, "summary": summary})


