def n(qid: int) -> str:
    return f"《{TASKS[qid]['name']}》"


def names(*qids: int) -> str:
    return " + ".join(n(qid) for qid in qids)


points: list[list[Any]] = []
covered: set[int] = set()
step_groups: list[dict[str, Any]] = []


def P(
    x: float,
    y: float,
    title: str,
    action: str,
    phase: str,
    note: str = "",
    movement: str = "ride",
    qids: tuple[int, ...] = (),
    optional: bool = False,
    fivebox_check: str = "",
) -> None:
    # qids are retained as hidden structural metadata for estimators/audits. Player-facing
    # renderers continue to use fields 0-8 only, so copy can be edited for readability
    # without changing objective accounting.
    points.append([x, y, title, action, phase, note, movement, optional, fivebox_check, list(qids)])
    covered.update(qids)


def G(title: str, summary: str, fn) -> None:
    start = len(points)
    fn()
    end = len(points) - 1
    if end < start:
        raise RuntimeError(f"empty group: {title}")
    step_groups.append({"start": start, "end": end, "title": title, "summary": summary})


